// Records every fixed line of dialog with ElevenLabs, one voice per character.
//
//   1. VOICE_LINES=1 npx vitest run src/audio/voiceLines.test.ts   (writes scripts/voice-lines.json)
//   2. ELEVENLABS_API_KEY=... node scripts/voice.mjs [--only pip,gran] [--redo]
//
// Casting is scripts/voices.json: a library voice id, or a "design" description that is turned
// into a new voice once (its id is written back, so reruns reuse it). Lines already recorded in
// assets/voice are skipped unless --redo. Writes src/audio/voices.generated.ts.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const KEY = process.env.ELEVENLABS_API_KEY;
if (!KEY) throw new Error('Set ELEVENLABS_API_KEY');
const API = 'https://api.elevenlabs.io';
const MODEL = 'eleven_multilingual_v2';
const OUT = 'assets/voice';
const CAST_FILE = 'scripts/voices.json';

const args = process.argv.slice(2);
const only = args.includes('--only') ? new Set(args[args.indexOf('--only') + 1].split(',')) : null;
const redo = args.includes('--redo');

const cast = JSON.parse(readFileSync(CAST_FILE, 'utf8'));
const lines = JSON.parse(readFileSync('scripts/voice-lines.json', 'utf8'));
mkdirSync(OUT, { recursive: true });

async function call(path, body, raw = false) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(API + path, {
      method: 'POST',
      headers: { 'xi-api-key': KEY, 'content-type': 'application/json' },
      body: JSON.stringify(body),
    });
    if (res.ok) return raw ? Buffer.from(await res.arrayBuffer()) : res.json();
    const msg = (await res.text()).slice(0, 300);
    // Busy (too many at once) or a blip: wait and try again a few times.
    if ((res.status === 429 || res.status >= 500) && attempt < 4) {
      await new Promise((r) => setTimeout(r, 2000 * (attempt + 1)));
      continue;
    }
    throw new Error(`${path}: ${res.status} ${msg}`);
  }
}

/** Design a voice from its description and save it to the account; returns the new voice id. */
async function design(who, description) {
  const d = await call('/v1/text-to-voice/design', {
    voice_description: description,
    model_id: 'eleven_multilingual_ttv_v2',
    auto_generate_text: true,
  });
  const preview = d.previews?.[0];
  if (!preview) throw new Error(`no preview for ${who}`);
  const saved = await call('/v1/text-to-voice', {
    voice_name: `Glowire ${who}`,
    voice_description: description,
    generated_voice_id: preview.generated_voice_id,
  });
  return saved.voice_id;
}

/** What the voice actor reads: symbols spelled out, decoration dropped. */
const spoken = (t) =>
  t
    .replace(/÷/g, ' divided by ')
    .replace(/≈/g, ' about ')
    .replace(/(\d)\s*Ω/g, '$1 ohms')
    .replace(/(\d)\s*mA\b/g, '$1 milliamps')
    .replace(/(\d)\s*V\b/g, '$1 volts')
    .replace(/[⚡✦◆◉✎≈♪]/gu, '')
    .replace(/\s+/g, ' ')
    .trim();

for (const [who, c] of Object.entries(cast)) {
  if (c.voice || (only && !only.has(who))) continue;
  process.stdout.write(`designing ${who}… `);
  try {
    c.voice = await design(who, c.design);
  } catch (e) {
    console.log(`skipped (${String(e.message).slice(0, 160)})`);
    continue;
  }
  writeFileSync(CAST_FILE, JSON.stringify(cast, null, 2) + '\n');
  console.log(c.voice);
}

const todo = lines.filter(
  (l) => cast[l.who]?.voice && (!only || only.has(l.who)) && (redo || !existsSync(`${OUT}/${l.key}.mp3`)),
);
console.log(`${todo.length} lines to record, ${todo.reduce((n, l) => n + l.text.length, 0)} characters`);
let done = 0;
async function worker() {
  for (let l; (l = todo.shift()); ) {
    const mp3 = await call(
      `/v1/text-to-speech/${cast[l.who].voice}?output_format=mp3_22050_32`,
      { text: spoken(l.text), model_id: MODEL },
      true,
    );
    writeFileSync(`${OUT}/${l.key}.mp3`, mp3);
    if (++done % 25 === 0) console.log(`${done} recorded`);
  }
}
await Promise.all([worker(), worker(), worker(), worker()]);

// The require map the game plays from: only lines that have a recording.
const have = lines.filter((l) => existsSync(`${OUT}/${l.key}.mp3`)).sort((a, b) => a.key.localeCompare(b.key));
writeFileSync(
  'src/audio/voices.generated.ts',
  '// Generated by scripts/voice.mjs. Do not edit.\n\n' +
    'export const VOICES: Record<string, number> = {\n' +
    have.map((l) => `  '${l.key}': require('../../assets/voice/${l.key}.mp3'),`).join('\n') +
    '\n};\n',
);
console.log(`done: ${done} new, ${have.length} lines voiced`);
